'use strict';
const assert=require('node:assert/strict');
const store=new Map();
global.localStorage={getItem:k=>store.has(k)?store.get(k):null,setItem:(k,v)=>store.set(k,String(v))};
global.window={};
const Logic=require('./motor_logico.js');global.MindLogic=window.MindLogic=Logic;
const Knowledge=require('./conocimiento.js');window.MindKnowledge=Knowledge;
const Sugeridor=require('./sugeridor.js');global.Sugeridor=window.Sugeridor=Sugeridor;
const Clasico=require('./clasico.js');global.Clasico=window.Clasico=Clasico;
const candidates=Array.from({length:900},(_,i)=>({nombre:`Candidato ${i}`,tipo:i%3===0?'real':'ficticio',real:i%3===0,ficticio:i%3!==0,humano:i%3===0,genero:i%2?'hombre':'mujer',vivo:i%4===0,universo:['historia','fantasia','ciencia','anime'][i%4],medios:[['libro'],['videojuego'],['pelicula'],['television']][i%4],etiquetas:[['cientifico'],['guerrero'],['artista'],['deportista']][i%4],poderes:i%5===0,combate:i%3===1}));
(async()=>{
 let yields=0;const original=global.setTimeout;global.setTimeout=(fn,ms,...args)=>{if(ms===0)yields++;return original(fn,ms,...args)};
 const s=Clasico.nuevo(candidates);
 const q=await Clasico.preguntaAsync(s,Logic);
 assert.ok(q,'debe seleccionar una pregunta');
 assert.ok(yields>0,'la selección debe ceder el hilo al navegador');
 const before=s.w.slice();
 await Clasico.responderAsync(s,Logic,q,'si');
 assert.equal(s.n,1);assert.equal(s.log.length,1);assert.equal(s.asked.has(Logic.normalizar(q)),true);
 assert.ok(yields>=2,'el cálculo de respuesta de 900 candidatos debe dividirse en bloques');
 assert.ok(s.w.some((w,i)=>w!==before[i]),'las ponderaciones deben actualizarse');
 Sugeridor.invalidarCache();
 const second=await Clasico.preguntaAsync(s,Logic);
 assert.ok(second,'debe calcular una segunda pregunta');
 assert.equal(Clasico.esRedundante(s,Logic,second),false,'no debe repetir concepto');
 const filtered=await Clasico.descartarContradichosAsync(s,Logic,2);
 assert.ok(filtered&&Array.isArray(filtered.descartados));
 global.setTimeout=original;
 console.log(`PASS procesamiento cooperativo: ${yields} cesiones al navegador; respuesta y selección asíncronas en 900 candidatos.`);
 console.log('PASS continuidad lógica: respuesta registrada, pesos actualizados y segunda pregunta sin repetición semántica.');
 console.log('PASS filtrado cooperativo de contradicciones.');
})().catch(e=>{console.error(e);process.exit(1)});
